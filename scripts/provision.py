#!/usr/bin/env python3
"""
Generate the firmware's compile-time configuration from config/default.json
merged with config/user.json.

Run from the project root:
    python scripts/provision.py
"""

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "mac"))

from config import PARAMETERS, DEFAULT_PARAMETER  # noqa: E402

PARAMETER_ORDER = (
    "exposure",
    "contrast",
    "highlights",
    "shadows",
    "whites",
    "blacks",
    "temperature",
    "saturation",
)


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def main() -> None:
    if set(PARAMETERS) != set(PARAMETER_ORDER):
        raise ValueError(
            "The firmware requires exactly these eight parameters: "
            + ", ".join(PARAMETER_ORDER)
        )

    enabled = [
        bool(PARAMETERS[key].get("enabled", True))
        for key in PARAMETER_ORDER
    ]
    if not any(enabled):
        raise ValueError("At least one controller parameter must be enabled.")

    if DEFAULT_PARAMETER not in PARAMETER_ORDER:
        raise ValueError("The default parameter is not supported by firmware.")

    default_index = PARAMETER_ORDER.index(DEFAULT_PARAMETER)
    if not enabled[default_index]:
        default_index = enabled.index(True)

    names = [PARAMETERS[key]["label"] for key in PARAMETER_ORDER]
    labels = [PARAMETERS[key]["short_label"] for key in PARAMETER_ORDER]

    content = f"""#pragma once

#include <Arduino.h>

// Generated by scripts/provision.py. Do not edit manually.
namespace LumenConfig {{

constexpr uint8_t PARAMETER_COUNT = 8;
constexpr uint8_t DEFAULT_PARAMETER_INDEX = {default_index};

static const char* const PARAMETER_KEYS[PARAMETER_COUNT] = {{
    {", ".join(cpp_string(key) for key in PARAMETER_ORDER)}
}};

static const char* const PARAMETER_NAMES[PARAMETER_COUNT] = {{
    {", ".join(cpp_string(value) for value in names)}
}};

static const char* const PARAMETER_LABELS[PARAMETER_COUNT] = {{
    {", ".join(cpp_string(value) for value in labels)}
}};

static const bool PARAMETER_ENABLED[PARAMETER_COUNT] = {{
    {", ".join("true" if value else "false" for value in enabled)}
}};

}} // namespace LumenConfig
"""

    output = PROJECT_ROOT / "firmware" / "src" / "generated_config.h"
    output.write_text(content, encoding="utf-8")
    print(f"Generated: {output.relative_to(PROJECT_ROOT)}")
    print(f"Default parameter: {PARAMETER_ORDER[default_index]}")
    print("Enabled: " + ", ".join(
        key for key, is_enabled in zip(PARAMETER_ORDER, enabled) if is_enabled
    ))


if __name__ == "__main__":
    main()
